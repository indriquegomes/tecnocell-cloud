const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const operador='00000000-0000-4000-8000-000000000001';
const outro='00000000-0000-4000-8000-000000000002';
const pedido='00000000-0000-4000-8000-000000000003';
test('operação: versão protege disputa, eventos não alteram financeiro e acesso App é negado',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create table pedidos_app(id uuid primary key,status text,itens jsonb);
 create table vendas(id uuid primary key,status text);
 create table itens_venda(venda_id uuid,produto_id text,quantidade numeric);
 create table devolucoes(id uuid primary key,venda_id uuid,status text);
 create table itens_devolucao(devolucao_id uuid,produto_id text,quantidade numeric);
 create table pedidos_app_unidades(unidade text primary key);
 insert into pedidos_app_unidades values('Petrópolis');
 create table pedidos_app_atendimentos(pedido_id uuid,unidade text,venda_id uuid,confirmado_em timestamptz,primary key(pedido_id,unidade));
 create function validar_operador_pedido_app(uuid,text) returns void language plpgsql as $$begin if $2<>'Petrópolis' then raise exception 'Não autorizado'; end if; end$$;
 insert into pedidos_app values('${pedido}','pendente','[{"loja":"Petrópolis"}]');
 `);
 const reversao=fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261020040612_pedido_app_devolucao_integral.sql'),'utf8').match(/create function public\.pedido_app_venda_revertida[\s\S]*?\$\$;/)[0];
 await db.exec(reversao);
 await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261020171728_pedidos_app_operacao.sql'),'utf8'));
 const acao=(ator,versao,tipo)=>db.query('select registrar_operacao_pedido_app($1,$2,$3,$4,$5)',[pedido,'Petrópolis',ator,versao,tipo]);
 await acao(operador,0,'assumir');
 await assert.rejects(acao(outro,0,'assumir'),/atualiz/i);
 await assert.rejects(acao(outro,1,'separado'),/respons/i);
 await assert.rejects(acao(operador,1,'entregue'),/venda/i);
 await acao(operador,1,'impressao_solicitada');
 await acao(operador,2,'papel_confirmado');
 await acao(operador,3,'separado');
 assert.equal((await db.query('select count(*)::int n from pedidos_app_operacao_eventos')).rows[0].n,4);
 assert.equal((await db.query('select status from pedidos_app')).rows[0].status,'pendente');
 assert.equal((await db.query('select count(*)::int n from vendas')).rows[0].n,0);
 assert.equal((await db.query('select count(*)::int n from pedidos_app_atendimentos')).rows[0].n,0,'assumir não confirma disponibilidade nem cria vínculo financeiro');
 await assert.rejects(db.query('select registrar_operacao_pedido_app($1,$2,$3,$4,$5)',[pedido,'Outra',operador,4,'assumir']),/autoriz/i);
 await db.exec(`insert into vendas values('${pedido}','concluida');
 insert into pedidos_app_atendimentos values('${pedido}','Petrópolis','${pedido}',null);
 insert into itens_venda values('${pedido}','peca',1);
 insert into devolucoes values('${pedido}','${pedido}','concluida');
 insert into itens_devolucao values('${pedido}','peca',1);`);
 await assert.rejects(acao(operador,4,'entregue'),/venda/i,'helper SQL real bloqueia entrega de venda integralmente devolvida');
 await db.exec(`update devolucoes set status='cancelada'`);
 await acao(operador,4,'entregue');
 await assert.rejects(acao(operador,5,'entregue'),/já registrada/i);
 await db.exec('set role authenticated');
 await assert.rejects(acao(operador,4,'assumir'),/permission denied/i);
 }finally{await db.close()}
});
